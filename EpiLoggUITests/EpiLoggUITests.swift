    func testOnboardingValidatesMedicationBeforeLeavingStep() {
        continueAfterFailure = false
        let app = XCUIApplication()
        app.launch()
        XCTAssertTrue(app.buttons["onboarding.start"].waitForExistence(timeout: 10))
        app.buttons["onboarding.start"].tap()
        app.buttons["onboarding.next"].tap()
        app.buttons["Legg til medisin"].tap()
        app.buttons["onboarding.next"].tap()

        let validationAlert = app.alerts["Kontroller opplysningene"]
        XCTAssertTrue(validationAlert.waitForExistence(timeout: 5))
        XCTAssertTrue(validationAlert.staticTexts["Skriv navnet på medisinen, eller fjern den tomme medisinen."].exists)
        validationAlert.buttons["OK"].tap()
        XCTAssertTrue(app.staticTexts["Medisinene dine"].exists)
        XCTAssertFalse(app.staticTexts["Mulige triggere"].exists)

        app.textFields["Dose (valgfritt)"].tap()
        app.textFields["Dose (valgfritt)"].typeText("100 mg")
        app.buttons["Hopp over dette steget"].tap()
        XCTAssertTrue(validationAlert.waitForExistence(timeout: 5))
        validationAlert.buttons["OK"].tap()
        XCTAssertEqual(app.textFields["Dose (valgfritt)"].value as? String, "100 mg")
        app.textFields["Navn på medisin"].tap()
        app.textFields["Navn på medisin"].typeText("Medisin A\n")
        scrollTo(app.buttons["Legg til medisin"], in: app)
        app.buttons["Legg til medisin"].tap()
        let secondName = app.textFields.matching(identifier: "Navn på medisin").element(boundBy: 1)
        scrollTo(secondName, in: app)
        secondName.tap()
        secondName.typeText("   \n")
        app.buttons["onboarding.next"].tap()
        XCTAssertTrue(validationAlert.waitForExistence(timeout: 5))
        validationAlert.buttons["OK"].tap()
        app.buttons["Fjern medisin 2"].tap()
        app.buttons["onboarding.next"].tap()
        XCTAssertTrue(app.staticTexts["Mulige triggere"].waitForExistence(timeout: 5))

        app.buttons["onboarding.back"].tap()
        XCTAssertTrue(app.staticTexts["Medisinene dine"].waitForExistence(timeout: 5))
        XCTAssertEqual(app.textFields["Navn på medisin"].value as? String, "Medisin A")
        XCTAssertEqual(app.textFields["Dose (valgfritt)"].value as? String, "100 mg")
        app.buttons["onboarding.next"].tap()
        app.buttons["onboarding.next"].tap()
        app.buttons["onboarding.next"].tap()
        XCTAssertTrue(app.buttons["onboarding.finish"].waitForExistence(timeout: 5))
        app.buttons["onboarding.back"].tap()
        XCTAssertTrue(app.staticTexts["Dine steder"].waitForExistence(timeout: 5))
        app.buttons["onboarding.next"].tap()
        app.buttons["onboarding.finish"].tap()
        XCTAssertTrue(app.buttons["seizure.add"].waitForExistence(timeout: 5))
        XCTAssertFalse(app.alerts.firstMatch.exists)
        app.tabBars.buttons["Profil"].tap()
        scrollTo(app.staticTexts["Medisin A"], in: app)
        XCTAssertTrue(app.staticTexts["Medisin A"].exists)
        scrollTo(app.buttons["profile.deleteAll"], in: app)
        app.buttons["profile.deleteAll"].tap()
        app.sheets.buttons["Slett alle data"].tap()
        XCTAssertTrue(app.buttons["onboarding.start"].waitForExistence(timeout: 5))
    }

    private func scrollTo(_ element: XCUIElement, in app: XCUIApplication) {
        for _ in 0..<8 {
            if element.exists && element.isHittable { return }
            app.scrollViews.firstMatch.swipeUp()
        }
        XCTAssertTrue(element.isHittable)
    }
